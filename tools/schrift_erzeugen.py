def tabelle(name, font, h):
    zeilen = []
    for ch, g in font.items():
        w = len(g[0]); assert all(len(r) == w for r in g) and len(g) == h, ch
        bits = [int(r.replace("#", "1").replace(".", "0"), 2) for r in g] + [0] * (7 - h)
        c = "'\\xB0'" if ch == "°" else f"'{ch}'"   # Grad als Byte 0xB0 (Latin-1), im C-Text "\xB0"
        zeilen.append(f"  {{{c}, {w}, {{{', '.join(f'0x{b:02X}' for b in bits)}}}}},")
    return f"static const Glyph {name}[] = {{\n" + "\n".join(zeilen) + f"\n}};\n#define {name}_N {len(font)}\n#define {name}_H {h}\n"

def breite(text, font, sc=1):
    return sum((len(font[c][0]) + 1) * sc for c in text) - sc

